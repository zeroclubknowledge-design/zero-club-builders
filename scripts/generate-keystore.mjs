#!/usr/bin/env node
/**
 * Creates the Android upload keystore for Zero Club.
 *
 * Read this before running it:
 *
 *   The key produced here identifies the app to Google Play. If you enrol in
 *   Play App Signing (the default for new apps) this is the *upload* key and
 *   Google can reset it if you lose it. If you do NOT enrol, it is the app
 *   signing key, and losing it means you can never update the listing again.
 *   Either way: back the file up somewhere durable and never commit it.
 *
 * The keystore lands at android/android.keystore and the passwords at
 * android/keystore.properties. Both are gitignored — verify with:
 *   git check-ignore -v android/android.keystore android/keystore.properties
 *
 * Usage:
 *   node scripts/generate-keystore.mjs
 *   node scripts/generate-keystore.mjs --force        # replace an existing keystore
 *
 * Passwords are taken from BUBBLEWRAP_KEYSTORE_PASSWORD / BUBBLEWRAP_KEY_PASSWORD
 * if set, otherwise prompted for without echo.
 */

import { writeFile, readFile, chmod } from "node:fs/promises";
import {
  ANDROID_DIR,
  BuildError,
  KEYSTORE_PATH,
  KEYSTORE_PROPERTIES,
  TWA_MANIFEST,
  exists,
  keytoolPath,
  log,
  prompt,
  promptHidden,
  resolveJdk,
  run,
  warn,
} from "./lib/android-env.mjs";

/** 30 years. Play requires a key valid past 22 Oct 2033. */
const VALIDITY_DAYS = 10950;
const KEY_SIZE = 4096;

async function collectPasswords() {
  const fromEnv = {
    store: process.env.BUBBLEWRAP_KEYSTORE_PASSWORD,
    key: process.env.BUBBLEWRAP_KEY_PASSWORD,
  };
  if (fromEnv.store && fromEnv.key) {
    log("Using passwords from BUBBLEWRAP_KEYSTORE_PASSWORD / BUBBLEWRAP_KEY_PASSWORD.");
    return { store: fromEnv.store, key: fromEnv.key };
  }

  if (!process.stdin.isTTY) {
    throw new BuildError(
      "No TTY and no password environment variables.\n" +
        "  Set BUBBLEWRAP_KEYSTORE_PASSWORD and BUBBLEWRAP_KEY_PASSWORD, or run this interactively.",
    );
  }

  const store = await promptHidden("Keystore password (min 6 chars): ");
  if (store.length < 6) throw new BuildError("Keystore password must be at least 6 characters.");
  const confirm = await promptHidden("Confirm keystore password: ");
  if (store !== confirm) throw new BuildError("Passwords did not match.");

  // Using one password for both is normal for a single-key upload keystore and
  // is what Bubblewrap and the CI workflow assume.
  return { store, key: store };
}

async function main() {
  const force = process.argv.includes("--force");

  if ((await exists(KEYSTORE_PATH)) && !force) {
    warn(`A keystore already exists at ${KEYSTORE_PATH}`);
    warn("Refusing to overwrite it. If this app is already on Play, replacing the");
    warn("upload key requires a key reset request in the Play Console.");
    warn("Pass --force only if you are certain the existing key was never published.");
    process.exit(1);
  }

  const jdkPath = await resolveJdk();
  const keytool = keytoolPath(jdkPath);
  log(`Using keytool from ${jdkPath}`);

  const manifest = JSON.parse(await readFile(TWA_MANIFEST, "utf8"));
  const alias = manifest.signingKey?.alias ?? "zeroclub-upload";

  const org = process.stdin.isTTY
    ? (await prompt("Organisation name [Zero Club]: ")) || "Zero Club"
    : "Zero Club";
  const country = process.stdin.isTTY
    ? (await prompt("Two-letter country code [GB]: ")) || "GB"
    : "GB";

  if (!/^[A-Za-z]{2}$/.test(country)) {
    throw new BuildError(`Country must be a two-letter ISO code, got "${country}"`);
  }

  const passwords = await collectPasswords();

  log(`Generating a ${KEY_SIZE}-bit RSA key valid for ${VALIDITY_DAYS} days...`);
  await run(
    keytool,
    [
      "-genkeypair",
      "-keystore",
      KEYSTORE_PATH,
      "-alias",
      alias,
      "-keyalg",
      "RSA",
      "-keysize",
      String(KEY_SIZE),
      "-validity",
      String(VALIDITY_DAYS),
      // PKCS12 is the portable, non-deprecated format. JKS triggers a warning
      // from keytool and is being phased out.
      "-storetype",
      "PKCS12",
      "-dname",
      `CN=${org}, O=${org}, C=${country.toUpperCase()}`,
      "-storepass",
      passwords.store,
      "-keypass",
      passwords.key,
    ],
    { cwd: ANDROID_DIR, capture: true, redact: [passwords.store, passwords.key] },
  );

  await writeFile(
    KEYSTORE_PROPERTIES,
    [
      "# Generated by scripts/generate-keystore.mjs.",
      "# GITIGNORED - never commit this file, and never paste its contents anywhere.",
      "#",
      "# The build scripts read these, but environment variables of the same purpose",
      "# (BUBBLEWRAP_KEYSTORE_PASSWORD / BUBBLEWRAP_KEY_PASSWORD) take precedence,",
      "# which is how CI supplies them without writing a file.",
      "",
      `storeFile=android.keystore`,
      `keyAlias=${alias}`,
      `storePassword=${passwords.store}`,
      `keyPassword=${passwords.key}`,
      "",
    ].join("\n"),
    "utf8",
  );

  // Best effort on POSIX; a no-op on Windows.
  await chmod(KEYSTORE_PATH, 0o600).catch(() => {});
  await chmod(KEYSTORE_PROPERTIES, 0o600).catch(() => {});

  log(`Keystore written to ${KEYSTORE_PATH}`);
  log(`Passwords written to ${KEYSTORE_PROPERTIES}`);
  console.log("");
  console.log("Next steps:");
  console.log("  1. Back up android/android.keystore somewhere durable and private.");
  console.log("  2. node scripts/write-assetlinks.mjs     # bake the fingerprint into the site");
  console.log(
    "  3. Deploy, then confirm https://zeroclubs.xyz/.well-known/assetlinks.json is live.",
  );
  console.log("  4. node scripts/build-android.mjs        # produce the APK and AAB");
  console.log("");
  console.log("  For CI, add these repository secrets:");
  console.log("    ANDROID_KEYSTORE_BASE64   base64 of android/android.keystore");
  console.log("    ANDROID_KEYSTORE_PASSWORD");
  console.log("    ANDROID_KEY_PASSWORD");
  console.log("  Encode the keystore with:");
  console.log("    node scripts/write-assetlinks.mjs --print-secret");
}

main().catch((error) => {
  console.error(`\nx ${error.message}`);
  process.exit(1);
});
